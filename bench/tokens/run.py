"""Counts tokens for each dataset in every format and writes RESULTS.md.

Formats: JSON (pretty and minified), YAML, TOON (from encode_toon.mjs), and
AXS (from `axs from-json`). Every AXS output is converted back with
`axs to-json` and must equal the input.
"""

import json
import os
import subprocess
from pathlib import Path

import tiktoken
import yaml
from tokenizers import Tokenizer

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
AXS = os.environ.get("AXS_BIN", str(ROOT / "target" / "debug" / "axs"))
FORMATS = ["json_pretty", "json_min", "yaml", "toon", "axs"]
LABELS = {
    "json_pretty": "JSON (indent 2)",
    "json_min": "JSON (minified)",
    "yaml": "YAML",
    "toon": "TOON",
    "axs": "AXS",
}


def tokenizers():
    llama = Tokenizer.from_pretrained("Xenova/llama3-tokenizer-new")
    return {
        "o200k_base (GPT-4o, GPT-5)": tiktoken.get_encoding("o200k_base").encode,
        "cl100k_base (GPT-4)": tiktoken.get_encoding("cl100k_base").encode,
        "Llama 3": lambda text: llama.encode(text, add_special_tokens=False).ids,
    }


def axs(command, path):
    return subprocess.run([AXS, command, "--", str(path)], check=True,
                          capture_output=True, text=True).stdout


def encodings(name):
    source = HERE / "data" / f"{name}.json"
    value = json.loads(source.read_text())
    out = HERE / "out"
    axs_text = axs("from-json", source)
    axs_path = out / f"{name}.axs"
    axs_path.write_text(axs_text)
    if json.loads(axs("to-json", axs_path)) != value:
        raise SystemExit(f"{name}: AXS output does not convert back to the input")
    return {
        "json_pretty": json.dumps(value, ensure_ascii=False, indent=2),
        "json_min": json.dumps(value, ensure_ascii=False, separators=(",", ":")),
        "yaml": yaml.safe_dump(value, allow_unicode=True, sort_keys=False),
        "toon": (out / f"{name}.toon").read_text(),
        "axs": axs_text,
    }


def percent(count, baseline):
    return f"{(count - baseline) / baseline * 100:+.1f}%"


def main():
    subprocess.run(["node", str(HERE / "encode_toon.mjs")], check=True)
    names = sorted(path.stem for path in (HERE / "data").glob("*.json"))
    counters = tokenizers()
    texts = {name: encodings(name) for name in names}

    lines = [
        "# Token benchmark results",
        "",
        "Generated by `run.py`; do not edit by hand. Percentages compare with",
        "minified JSON for the same dataset and tokenizer (negative is fewer",
        "tokens). See README.md for the method.",
        "",
    ]
    totals = {}
    for tokenizer, encode in counters.items():
        lines += [f"## {tokenizer}", "",
                  "| Dataset | " + " | ".join(LABELS[f] for f in FORMATS) + " |",
                  "|---|" + "---:|" * len(FORMATS)]
        sums = dict.fromkeys(FORMATS, 0)
        for name in names:
            counts = {f: len(encode(texts[name][f])) for f in FORMATS}
            for f in FORMATS:
                sums[f] += counts[f]
            cells = [str(counts["json_pretty"]), str(counts["json_min"])] + [
                f"{counts[f]} ({percent(counts[f], counts['json_min'])})"
                for f in FORMATS[2:]]
            lines.append(f"| {name} | " + " | ".join(cells) + " |")
        cells = [str(sums["json_pretty"]), str(sums["json_min"])] + [
            f"**{sums[f]}** ({percent(sums[f], sums['json_min'])})" for f in FORMATS[2:]]
        lines += [f"| **total** | " + " | ".join(cells) + " |", ""]
        totals[tokenizer] = sums

    lines += ["## Characters", "",
              "| Dataset | " + " | ".join(LABELS[f] for f in FORMATS) + " |",
              "|---|" + "---:|" * len(FORMATS)]
    for name in names:
        lines.append(f"| {name} | " + " | ".join(str(len(texts[name][f])) for f in FORMATS) + " |")
    lines.append("")

    (HERE / "RESULTS.md").write_text("\n".join(lines))
    for tokenizer, sums in totals.items():
        summary = ", ".join(f"{LABELS[f]} {sums[f]}" for f in FORMATS)
        print(f"{tokenizer}: {summary}")


if __name__ == "__main__":
    main()
